// Writes docs/MODULE_GUIDE.md from the same data the in-app Guide shows (src/modules/guide/guideData.js), so the written guide and the
// screens cannot drift apart.
//
//   node scripts/build-guide-docs.mjs           write docs/MODULE_GUIDE.md
//   node scripts/build-guide-docs.mjs --check   exit 1 when the file is out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');
const guideDir = path.join(root, 'frontend', 'src', 'modules', 'guide');
const target = path.join(root, 'docs', 'MODULE_GUIDE.md');

const d = await import(pathToFileURL(path.join(guideDir, 'guideData.js')).href);
const { MODULE_META } = await import(pathToFileURL(path.join(root, 'frontend', 'src', 'moduleMeta.js')).href);
const { OVERVIEW, FLOW_LANES, FLOW_STEPS, FLOWS, CROSS_CUTTING, GLOSSARY, MODULE_GUIDES, ROLES, PERMISSIONS, MATRIX, ROLE_NOTES } = d;

const name = (k) => d.nameOf(k);
const cell = (t) => String(t ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const anchor = (t) => t.toLowerCase().replace(/[^a-z0-9 -]/g, '').trim().replace(/ /g, '-');
const out = [];
const p = (...lines) => out.push(...lines);
const table = (head, rows) => {
  p(`| ${head.map(cell).join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`);
  rows.forEach((r) => p(`| ${r.map(cell).join(' | ')} |`));
  p('');
};

p('# Tera2Nano ERP: module guide', '',
  '> Generated from `frontend/src/modules/guide/guideData.js` (and `guideModulesA.js`, `guideModulesB.js`, `rolesData.js`) by',
  '> `frontend/scripts/build-guide-docs.mjs`. Do not edit this file by hand: change the data, then run `node scripts/build-guide-docs.mjs` in `frontend/`.',
  '> The in-app Guide (the Guide tile on the launcher, `/guide`) shows exactly the same content.', '');

p('## Contents', '',
  '1. [What this system is](#what-this-system-is)',
  '2. [The process from end to end](#the-process-from-end-to-end)',
  '3. [How the modules connect](#how-the-modules-connect)',
  `4. Module guides: ${MODULE_GUIDES.map((g) => `[${g.name}](#${anchor(g.name)})`).join(', ')}`,
  '5. [Roles and access](#roles-and-access)',
  '6. [Glossary](#glossary)', '');

// ---- 1
p('## What this system is', '');
OVERVIEW.intro.forEach((t) => p(t, ''));
OVERVIEW.howToRead.forEach((t) => p(`- ${t}`));
p('');
OVERVIEW.notes.forEach((t) => p(`*${t}*`, ''));

// ---- 2
p('## The process from end to end', '',
  'Read the lanes top to bottom. Step numbers match the numbers on the diagram in the app, where every box opens the real screen and "Play the process" walks through them.', '',
  '```text',
  FLOW_STEPS.filter((s) => s.lane === 'main').map((s) => s.title).join('  ->  '),
  '```', '');

const line = (id) => FLOW_STEPS.findIndex((s) => s.id === id) + 1;
p('```mermaid', 'flowchart LR');
FLOW_LANES.forEach((lane) => {
  const steps = FLOW_STEPS.filter((s) => s.lane === lane.id);
  p(`  subgraph ${lane.id}["${lane.title}"]`);
  steps.forEach((s) => p(`    ${s.id}["${line(s.id)}. ${s.title}"]`));
  if (lane.id !== 'across') steps.slice(1).forEach((s, i) => p(`    ${steps[i].id} --> ${s.id}`));
  p('  end');
});
FLOW_LANES.filter((l) => l.end).forEach((lane) => {
  const steps = FLOW_STEPS.filter((s) => s.lane === lane.id);
  const first = steps[0].id;
  const last = steps[steps.length - 1].id;
  if (lane.end.text.startsWith('Posts')) p(`  ${last} -->|posts| books`);
  else if (lane.end.text.startsWith('Reads tagged')) p(`  books -.->|tagged lines| ${first}`);
  else if (lane.end.text.startsWith('Reads the tax')) p(`  tax -.->|due dates, read only| ${first}`);
});
p('```', '');

FLOW_LANES.forEach((lane) => {
  p(`### ${lane.title}`, '', `*${lane.note}*`, '');
  FLOW_STEPS.filter((s) => s.lane === lane.id).forEach((s) => {
    p(`${line(s.id)}. **${s.title}** (${name(s.module)}; screen: ${s.screen}, \`${s.to}\`)`,
      `   - What happens: ${s.what}`, `   - Data that moves: ${s.data}`);
    if (s.extras?.length) p(`   - Related screens: ${s.extras.map((e) => `${e.label} (\`${e.to}\`)`).join(', ')}`);
  });
  if (lane.end) p('', `Lane ends: ${lane.end.text} (\`${lane.end.to}\`).`);
  p('');
});

// ---- 3
p('## How the modules connect', '',
  'Each row of the table is derived from the list of flows below it, so the table, the map in the app and the module guides agree.', '');
table(['Module', 'Sends data to', 'Receives data from', 'Posts to the ledger?', 'Uses approvals?', 'Uses attachments?', 'Permission codes'],
  MODULE_GUIDES.map((g) => [
    g.name,
    g.sendsTo.length ? g.sendsTo.map(name).join(', ') : g.matrixNote?.sends || '-',
    g.receivesFrom.length ? g.receivesFrom.map(name).join(', ') : g.matrixNote?.receives || '-',
    g.ledger.posts ? (g.key === 'accounting' ? 'Yes (it is the ledger)' : 'Yes') : 'No',
    g.approvals.length ? `Yes: ${g.approvals.map((a) => a.kind).join(', ')}` : 'No',
    g.attachments.length ? `Yes: ${g.attachments.join(', ')}` : 'No',
    g.codes.map((c) => `\`${c}\``).join(' '),
  ]));
p('### The flows', '');
MODULE_GUIDES.forEach((g) => {
  const flows = FLOWS.filter((f) => f.from === g.key);
  if (!flows.length) return;
  p(`**${g.name} sends**`, '');
  flows.forEach((f) => p(`- To ${name(f.to)}, ${f.label}: ${f.detail}`));
  p('');
});
p('### Across all modules', '');
CROSS_CUTTING.forEach((c) => p(`- **${c.title}.** ${c.text}`));
p('');

// ---- 4
p('## Module guides', '');
MODULE_GUIDES.forEach((g) => {
  p(`### ${g.name}`, '', `*${g.purpose}.* In the app: \`/guide/${g.key}\`.`, '');
  p('#### What it is used for', '');
  g.usedFor.forEach((t) => p(t, ''));
  p('#### Who uses it', '', g.who, '');
  table(['Permission', 'What it allows', 'Roles that hold it by default'], d.roleRows(g.codes).map((r) => [`\`${r.code}\``, r.text, r.roles.join(', ') || 'None']));
  p('#### Key screens', '');
  g.screens.forEach((s) => p(`- **${s.label}** (\`${s.to}\`): ${s.text}`));
  p('', '#### Step-by-step workflow', '');
  g.steps.forEach((s, i) => {
    p(`${i + 1}. **${s.title}.** ${s.text}`);
    if (s.example) p(`   - *Example:* ${s.example}`);
  });
  p('', '#### Statuses and what each means', '');
  if (!g.statuses.length) p('This module has no statuses of its own: it only reads and presents figures.', '');
  g.statuses.forEach((s) => { p(`**${s.title}**`, ''); table(['Status', 'What it means'], s.items); });
  p('#### Connections to other modules', '', '**Sends to other modules**', '');
  if (g.sends.length) g.sends.forEach((f) => p(`- To ${name(f.to)}, ${f.label}: ${f.detail}`)); else p('- Nothing is sent to another module.');
  p('', '**Receives from other modules**', '');
  if (g.receives.length) g.receives.forEach((f) => p(`- From ${name(f.from)}, ${f.label}: ${f.detail}`)); else p('- Nothing is received from another module.');
  p('', `**Posting to the books.** ${g.ledger.text}`, '');
  if (g.approvals.length) { p('**Approvals**', ''); g.approvals.forEach((a) => p(`- ${a.kind}: ${a.text}`)); p(''); } else p('**Approvals.** None.', '');
  p(`**Attachments.** ${g.attachments.length ? `Files can be attached to: ${g.attachments.join(', ')}.` : 'This module has no attachment boxes.'}`, '');
  p('#### What the system does by itself', '');
  g.automatic.forEach((t) => p(`- ${t}`));
  p('', '#### Reports and exports', '');
  g.reports.forEach((t) => p(t, ''));
  p('#### Good to know', '');
  g.limits.forEach((t) => p(`- ${t}`));
  p('');
});

// ---- 5
p('## Roles and access', '', 'Default permissions from the permission matrix in `backend/apps/accounts/access.py`. An administrator can change any role except Admin in Users and Access, so check that screen for what is in force.', '');
ROLES.forEach((r) => p(`- **${r.label}** (${(MATRIX[r.value] || []).length} of ${PERMISSIONS.length} permissions): ${ROLE_NOTES[r.value]}`));
p('');
const groups = [...new Set(PERMISSIONS.map((x) => x.group))];
table(['Permission', 'What it allows', ...ROLES.map((r) => r.label)], groups.flatMap((grp) => [
  [`**${grp}**`, '', ...ROLES.map(() => '')],
  ...PERMISSIONS.filter((x) => x.group === grp).map((x) => [`\`${x.code}\``, x.text, ...ROLES.map((r) => ((MATRIX[r.value] || []).includes(x.code) ? 'yes' : '-'))]),
]));

// ---- 6
p('## Glossary', '');
GLOSSARY.forEach((g) => p(`- **${g.term}.** ${g.meaning}`));
p('');

const text = out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== text) { console.error('docs/MODULE_GUIDE.md is out of date: run node scripts/build-guide-docs.mjs'); process.exit(1); }
  console.log('docs/MODULE_GUIDE.md is up to date');
} else {
  fs.writeFileSync(target, text);
  console.log(`wrote ${path.relative(root, target)} (${text.split('\n').length} lines, ${MODULE_GUIDES.length} modules)`);
}
void MODULE_META;
