// Writes src/modules/guide/rolesData.js from backend/apps/accounts/access.py, so the Guide's roles table can never drift from the
// permission matrix the server enforces (the defaults; an administrator may change them in the app).
//
//   node scripts/build-roles-data.mjs           write the file
//   node scripts/build-roles-data.mjs --check   exit 1 when the file is out of date
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');
const target = path.join(root, 'frontend', 'src', 'modules', 'guide', 'rolesData.js');
const candidates = [process.env.T2N_PYTHON, path.join(root, 'backend', '.venv', 'Scripts', 'python.exe'),
  path.join(root, 'backend', '.venv', 'bin', 'python'), 'python3', 'python'].filter(Boolean);

const code = `
import json, sys
sys.path.insert(0, ${JSON.stringify(path.join(root, 'backend'))})
from apps.accounts import access
print(json.dumps({
  "roles": [{"value": v, "label": l} for v, l in access.ROLES],
  "permissions": [{"code": c, "text": t, "group": g} for c, t, g in access.PERMISSIONS],
  "matrix": {r: sorted(access.DEFAULT_MATRIX[r]) for r in access.ROLE_VALUES},
}))`;

function run() {
  let lastError;
  for (const py of candidates) {
    try { return JSON.parse(execFileSync(py, ['-c', code], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] })); } catch (e) { lastError = e; }
  }
  throw new Error(`Could not run Python to read access.py (set T2N_PYTHON): ${lastError?.message}`);
}

const data = run();
const out = `// GENERATED by scripts/build-roles-data.mjs from backend/apps/accounts/access.py. Do not edit by hand.
// These are the default permissions of each role; an administrator can change them under Administration > Users and Access.
export const ROLES = ${JSON.stringify(data.roles, null, 2)};

export const PERMISSIONS = ${JSON.stringify(data.permissions, null, 2)};

export const MATRIX = ${JSON.stringify(data.matrix, null, 2)};
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current.replace(/\r\n/g, '\n') !== out) { console.error('rolesData.js is out of date: run node scripts/build-roles-data.mjs'); process.exit(1); }
  console.log('rolesData.js matches access.py');
} else {
  fs.writeFileSync(target, out);
  console.log(`wrote ${path.relative(root, target)} (${data.roles.length} roles, ${data.permissions.length} permissions)`);
}
