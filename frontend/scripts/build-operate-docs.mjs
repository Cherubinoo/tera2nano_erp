// Writes docs/HOW_TO_OPERATE.md from the operating-manual chapters the in-app Guide shows
// (src/modules/guide/operate/*.json, ordered by src/modules/guide/operateMeta.js), so the written manual and the screens match.
//
//   node scripts/build-operate-docs.mjs           write docs/HOW_TO_OPERATE.md
//   node scripts/build-operate-docs.mjs --check   exit 1 when the file is out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');
const guideDir = path.join(root, 'frontend', 'src', 'modules', 'guide');
const chapterDir = path.join(guideDir, 'operate');
const target = path.join(root, 'docs', 'HOW_TO_OPERATE.md');

const { OPERATE_ORDER, OPERATE_INTRO } = await import(pathToFileURL(path.join(guideDir, 'operateMeta.js')).href);
const all = Object.fromEntries(fs.readdirSync(chapterDir).filter((f) => f.endsWith('.json')).map((f) => {
  const c = JSON.parse(fs.readFileSync(path.join(chapterDir, f), 'utf8'));
  return [c.key, c];
}));
const chapters = OPERATE_ORDER.map((k) => all[k]).filter(Boolean);
const unlisted = Object.keys(all).filter((k) => !OPERATE_ORDER.includes(k));
if (unlisted.length) console.warn(`Chapters not in OPERATE_ORDER (skipped): ${unlisted.join(', ')}`);

const cell = (t) => String(t ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
const anchor = (t) => t.toLowerCase().replace(/[^a-z0-9 -]/g, '').trim().replace(/ /g, '-');
const out = [];
const p = (...lines) => out.push(...lines);
const table = (head, rows) => {
  p(`| ${head.map(cell).join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`);
  rows.forEach((r) => p(`| ${r.map(cell).join(' | ')} |`));
  p('');
};
const list = (items) => { items.forEach((i) => p(`- ${i}`)); p(''); };

p('# Tera2Nano ERP: how to operate', '',
  '> Generated from `frontend/src/modules/guide/operate/*.json` (order in `operateMeta.js`) by `frontend/scripts/build-operate-docs.mjs`.',
  '> Do not edit this file by hand: change the chapter JSON, then run `npm run guide:operate` in `frontend/`.',
  '> The in-app Guide shows the same manual under **Guide > How to operate** (`/guide/operate`).', '',
  OPERATE_INTRO.lead, '', '## How to use this manual', '');
list(OPERATE_INTRO.howToUse);

p('## Contents', '');
chapters.forEach((c, i) => p(`${i + 1}. [${c.title}](#${anchor(c.title)}) (${c.tasks.length} tasks)`));
p('');

for (const c of chapters) {
  p(`## ${c.title}`, '', c.purpose, '');
  if (c.who?.length) { p('**Who uses it**', ''); table(['Role', 'What they do here'], c.who.map((w) => [w.role, w.does])); }
  if (c.before_you_start?.length) { p('**Before you start**', ''); list(c.before_you_start); }
  for (const t of c.tasks) {
    p(`### ${t.title}`, '');
    if (t.who) p(`- **Who:** ${t.who}`);
    if (t.where || t.route) p(`- **Where:** ${t.where || ''}${t.route ? ` (\`${t.route}\`)` : ''}`);
    p('');
    t.steps.forEach((s, i) => p(`${i + 1}. ${s}`));
    p('');
    if (t.result) p(`**What happens next:** ${t.result}`, '');
    if (t.tips?.length) { p('**Tips**', ''); list(t.tips); }
  }
  if (c.statuses?.length) { p(`### ${c.title}: statuses`, ''); table(['Status', 'What it means'], c.statuses.map((s) => [s.name, s.meaning])); }
  const r = c.routines || {};
  const rs = [['daily', 'Every day'], ['weekly', 'Every week'], ['monthly', 'Every month'], ['yearly', 'Every year']].filter(([k]) => r[k]?.length);
  if (rs.length) {
    p(`### ${c.title}: routines`, '');
    rs.forEach(([k, label]) => { p(`**${label}**`, ''); list(r[k]); });
  }
  if (c.common_problems?.length) { p(`### ${c.title}: common problems`, ''); table(['Problem', 'What to do'], c.common_problems.map((x) => [x.problem, x.fix])); }
  if (c.connected?.length) { p(`### ${c.title}: connections to other modules`, ''); list(c.connected); }
}

p('## More help', '',
  'For the end-to-end process, how the modules connect, roles and a glossary, open the Guide tile on the launcher (`/guide`) or read `docs/MODULE_GUIDE.md`.', '');

const text = out.join('\n');
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== text) { console.error('docs/HOW_TO_OPERATE.md is out of date: run npm run guide:operate'); process.exit(1); }
  console.log('docs/HOW_TO_OPERATE.md is up to date');
} else {
  fs.writeFileSync(target, text, 'utf8');
  console.log(`Wrote ${path.relative(root, target)} (${chapters.length} chapters, ${chapters.reduce((n, c) => n + c.tasks.length, 0)} tasks, ${out.length} lines)`);
}
